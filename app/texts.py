"""
КАРЬЕРНЫЙ ГАЙД БОТ — все тексты сообщений.

Каждое сообщение — отдельная функция, возвращающая шаблон текста.
Плейсхолдеры:
  {name}  — первое имя пользователя из Telegram (подставляется через render())
  {price} — стоимость в едином формате «790 ₽ / 8€»

Форматирование: HTML parse mode (Telegram Bot API):
  <b>...</b>                    — bold
  <i>...</i>                    — italic
  <blockquote>...</blockquote>  — цитата
Разметка закрыта строго парно, вложенные теги используются точечно.
"""

from html import escape as _esc

from config import PRICE_DISPLAY


def first_name(user_full_name: str) -> str:
    """Первое имя пользователя, безопасно экранированное для HTML."""
    trimmed = (user_full_name or "").strip()
    if not trimmed:
        return "друг"
    return _esc(trimmed.split()[0])


def render(template: str, user_full_name: str) -> str:
    """Подставляет {name} и {price} в шаблон."""
    return template.format(name=first_name(user_full_name), price=PRICE_DISPLAY)


