WARMUP_STEP_MINUTES = [30, 360, 920, 1440, 1680, 2880, 4320, 4920, 7200]


def warmup_interval_seconds(step_index: int) -> int | None:
    """
    Интервал (в секундах) до следующего шага прогрева с индексом step_index.
    Возвращает None, если шаг вне цепочки.
    """
    if 0 <= step_index < len(WARMUP_STEP_MINUTES):
        return WARMUP_STEP_MINUTES[step_index] * 60
    return None
